#!/usr/bin/env node
/**
 * Writes data/blechy-cases.mjs: the label and hint of each case of Blechy's first question in all eleven languages, so the
 * page matches typed text in any language without loading eleven tables. Run after a change to a `rescue.case.*` text.
 *
 *   node tools/blechy-cases.mjs
 */
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { CASES } from "../data/rescue.mjs";
import { LANGUAGES } from "../site/app/i18n.mjs";

export const OUT = fileURLToPath(new URL("../data/blechy-cases.mjs", import.meta.url));

export async function build() {
  const tables = {};
  for (const [id] of LANGUAGES) tables[id] = (await import(`../site/app/i18n-${id}.mjs`)).default;
  const cases = Object.fromEntries(CASES.map(c => [c.id, Object.fromEntries(LANGUAGES.map(([id]) => [id, [tables[id][c.label], tables[id][c.hint]]]))]));
  return `// Generated by tools/blechy-cases.mjs from the rescue.case.* texts; do not edit.\nexport const CASE_TEXTS = ${JSON.stringify(cases, null, 2)};\n`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) writeFileSync(OUT, await build());
