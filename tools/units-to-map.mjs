#!/usr/bin/env node
/**
 * Generate data/map/fx-params.mjs from data/units.json.
 *
 *   node tools/units-to-map.mjs
 *
 * units.json is the AGPL input from hacktribe-editor and stays the source;
 * an update from upstream is a new units.json and one run of this script.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { pathToFileURL } from "node:url";
import fx from "../data/map/fx.mjs";
import { labelFor } from "../data/map/fx-labels.mjs";
import ranges from "../data/map/fx-ranges.mjs";

const ROOT = new URL("../", import.meta.url);
const units = JSON.parse(readFileSync(new URL("data/units.json", ROOT), "utf8"));
const EVIDENCE = "derived:hacktribe-editor/src/hacktribe_editor/utils/ht_fx_ram_format.py";

// Choice lists named in the DSP's own text functions: [converter, RAM address of the function in the ARM image].
const ENVELOPE = ["envelopeSelect"];
const CHOICES = {
  "fx.ifx.0x01.envelope_select": [...ENVELOPE, 0xC0114AF8], "fx.mfx.0x28.envelope_select": [...ENVELOPE, 0xC0114AF8],
  "fx.ifx.0x02.envelope_select": [...ENVELOPE, 0xC010830A], "fx.mfx.0x29.envelope_select": [...ENVELOPE, 0xC010830A],
  "fx.ifx.0x05.envelope_select": [...ENVELOPE, 0xC01082AC], "fx.mfx.0x2a.envelope_select": [...ENVELOPE, 0xC01082AC],
  "fx.ifx.0x09.mask_type": ["maskType", 0xC0109090], "fx.mfx.0x3e.mask_type": ["maskType", 0xC0109090],
  "fx.ifx.0x0a.output_select": ["filterOutput", 0xC011429C],
  "fx.ifx.0x13.type": ["phaserType", 0xC011CEDE], "fx.mfx.0x33.type": ["phaserType", 0xC011CEDE],
  "fx.ifx.0x13.phase": ["phasePolarity", 0xC011CEA8], "fx.mfx.0x33.phase": ["phasePolarity", 0xC011CEA8],
  "fx.ifx.0x13.mod_wave": ["lfoWaveTriSin", 0xC011CE7C], "fx.mfx.0x33.mod_wave": ["lfoWaveTriSin", 0xC011CE7C],
  "fx.ifx.0x15.level_mod_source": ["modShape", 0xC0114650], "fx.mfx.0x35.level_mod_source": ["modShape", 0xC01185AA],
  "fx.ifx.0x15.level_mod_type": ["levelModType", 0xC01145F8], "fx.mfx.0x35.level_mod_type": ["levelModType", 0xC0118552],
  "fx.mfx.0x2d.mod_source": ["modShape", 0xC0117596],
  "fx.mfx.0x3b.mod_wave": ["lfoWaveTriSin", 0xC0115564], "fx.mfx.0x3b.fb_type": ["feedbackType", 0xC0115590],
  "fx.mfx.0x3f.loop_type": ["loopType", 0xC0118DE8], "fx.mfx.0x3f.step": ["looperStep", 0xC0118DB6],
  "fx.ifx.0x18.off_time_ratio": ["timeRatio", 0xC011B8E0], "fx.mfx.0x3b.off_time_ratio": ["timeRatio", 0xC011566C],
};

// Stage positions come from the record map, so a correction there reaches the parameters.
const { paramsFromDevice: PARAMS_FROM_DEVICE, paramStride: PARAM_STRIDE } = fx.meta;
const stage = fx.fields.find(f => f.id === "fx.stage.device");
const at = name => stage.where.offset + stage.repeat[0].names.indexOf(name) * stage.repeat[0].stride;
const STAGES = {
  ifx: { device: at("ifx1"), repeat: [{ ...stage.repeat[0], count: 2, names: ["ifx1", "ifx2"] }] },
  mfx: { device: at("mfx"), repeat: null },
};

export function generate() {
const DEFAULTS = {
  area: "fx", type: "u8", transport: ["ram", "firmware"], convert: "plain",
  range: [0, 127], source: "derived", evidence: EVIDENCE,
};

const fields = [];
for (const [key, kind] of [["ifx_device", "ifx"], ["mfx_device", "mfx"]]) {
  for (const [hexId, entry] of Object.entries(units[key])) {
    const device = Number(hexId);
    entry.params.forEach((p, index) => {
      const label = labelFor(p.name);
      const field = {
        id: `fx.${kind}.${hexId.toLowerCase()}.${p.name}`,
        label: { de: label.de, en: p.name },
        group: label.group,
        where: { offset: STAGES[kind].device + PARAMS_FROM_DEVICE + PARAM_STRIDE * index },
        when: { offset: STAGES[kind].device, equals: device },
        fxUnit: entry.unit,
        paramIndex: index,
      };
      if (label.flags.includes("s")) { field.convert = "onOff"; field.range = [0, 1]; }
      else {
        // A negative min means the byte holds the shown value minus min. A span of 0 to 0 declares nothing;
        // a positive min (only the decimator's bit depth) is neither shifted nor measured, so it keeps the plain view.
        const [min, max] = ranges.units[hexId.toLowerCase()]?.[index] ?? [0, 0];
        if (max > min) {
          field.range = min < 0 ? [0, max - min] : [0, max];
          if (min < 0) field.convert = `fxShift${-min}`;
          field.rangeEvidence = ranges.evidence;
        }
      }
      if (CHOICES[field.id]) {
        const [convert, ram] = CHOICES[field.id];
        const [min, max] = ranges.units[hexId.toLowerCase()][index];
        Object.assign(field, { convert, range: [0, max - min], rangeEvidence: ranges.evidence, choiceEvidence: `derived:vsb-table/0x${ram.toString(16).toUpperCase()}` });
      } else if (label.flags.includes("c")) field.fxChoice = true;
      if (label.flags.includes("x")) field.edit = "expert";
      if (STAGES[kind].repeat) field.repeat = "stages";
      fields.push(field);
    });
  }
}

const out = `// Generated by tools/units-to-map.mjs from data/units.json. Do not edit.
// The parameter order is what matters: a control map row stores a position in
// this list, not an address. Every field takes the defaults; "stages" stands
// for the repeat over both insert stages. "when" names the device byte, in the
// same stage, that must hold the unit for the field to mean anything.
export default {
  block: "fxRecord",
  generated: true,
  defaults: ${JSON.stringify(DEFAULTS)},
  repeats: { stages: ${JSON.stringify(STAGES.ifx.repeat)} },
  fields: [
${fields.map(f => "    " + JSON.stringify(f) + ",").join("\n")}
  ],
};
`;
return { out, count: fields.length };
}

if (process.argv[1] && pathToFileURL(process.argv[1]).href === import.meta.url) {
  const { out, count } = generate();
  writeFileSync(new URL("data/map/fx-params.mjs", ROOT), out);
  console.log(`${count} parameter fields`);
}
